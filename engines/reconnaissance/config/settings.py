import hashlib
import ipaddress
import os
import secrets
from dataclasses import dataclass, field
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from ..schemas.models import Assessment


def initialize(directory: Path) -> None:
    names = ("operator.token", "viewer.token", "signing.pem", "signing.pub")
    if any((directory / name).exists() for name in names):
        raise ValueError("Configuration already exists or is partial; initialization will not overwrite it")
    directory.mkdir(parents=True, exist_ok=True)
    directory.chmod(0o700)
    key = Ed25519PrivateKey.generate()
    files = {
        "operator.token": secrets.token_urlsafe(40).encode(),
        "viewer.token": secrets.token_urlsafe(40).encode(),
        "signing.pem": key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()),
        "signing.pub": key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo),
    }
    created = []
    try:
        for name, data in files.items():
            path = directory / name
            descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            created.append(path)
            with os.fdopen(descriptor, "wb") as output:
                output.write(data)
    except OSError:
        for path in created:
            path.unlink()
        raise


@dataclass
class Settings:
    config_dir: Path
    data_dir: Path
    allowed_cidrs: tuple[str, ...] = ()
    allowed_domains: tuple[str, ...] = ()
    nmap_version: str = ""
    enable_udp: bool = False
    max_targets: int = 8
    batch_size: int = 256
    scan_rate: int = 20
    command_timeout: int = 180
    print_ports: bool = True
    max_parallelism: int = 8
    operator_digest: str = field(init=False, repr=False)
    viewer_digest: str = field(init=False, repr=False)

    def __post_init__(self):
        for name in ("operator", "viewer"):
            path = self.config_dir / f"{name}.token"
            if path.stat().st_mode & 0o077:
                raise ValueError("API credential files must not be group/world accessible")
            token = path.read_text().strip()
            if len(token) < 32:
                raise ValueError("API credentials must be generated by recon-engine init")
            setattr(self, f"{name}_digest", hashlib.sha256(token.encode()).hexdigest())
        for value in self.allowed_cidrs:
            network = ipaddress.ip_network(value, strict=True)
            if network.prefixlen == 0:
                raise ValueError("Global catch-all scope is prohibited")
        if not 1 <= self.max_targets <= 32 or not 1 <= self.batch_size <= 1024 or not 1 <= self.scan_rate <= 100:
            raise ValueError("Invalid target, batch, or rate limit")
        if not 10 <= self.command_timeout <= 600:
            raise ValueError("Invalid command timeout")
        if not 1 <= self.max_parallelism <= 32:
            raise ValueError("Invalid scan concurrency limit")
        if self.operator_digest == self.viewer_digest:
            raise ValueError("Operator and viewer credentials must differ")

    @classmethod
    def environment(cls):
        return cls(
            Path(os.environ.get("RECON_CONFIG_DIR", ".recon-config")).resolve(),
            Path(os.environ.get("RECON_DATA_DIR", "data")).resolve(),
            tuple(filter(None, os.environ.get("RECON_ALLOWED_CIDRS", "").split(","))),
            tuple(value.lower().rstrip(".") for value in filter(None, os.environ.get("RECON_ALLOWED_DOMAINS", "").split(","))),
            os.environ.get("RECON_NMAP_VERSION", ""),
            os.environ.get("RECON_ENABLE_UDP", "") == "1",
            max_targets=int(os.environ.get("RECON_MAX_TARGETS", "8")),
            batch_size=int(os.environ.get("RECON_BATCH_SIZE", "256")),
            scan_rate=int(os.environ.get("RECON_SCAN_RATE", "20")),
            command_timeout=int(os.environ.get("RECON_COMMAND_TIMEOUT", "180")),
            print_ports=os.environ.get("RECON_PORT_CONSOLE", "1") == "1",
            max_parallelism=int(os.environ.get("RECON_MAX_PARALLELISM", "8")),
        )

    def role(self, token: str) -> str | None:
        digest = hashlib.sha256(token.encode()).hexdigest()
        if secrets.compare_digest(digest, self.operator_digest):
            return "operator"
        if secrets.compare_digest(digest, self.viewer_digest):
            return "viewer"
        return None

    def ip(self, value: str) -> str:
        address = ipaddress.ip_address(value)
        if "%" in value or address.is_link_local or address.is_unspecified or address.is_multicast:
            raise ValueError("Link-local, scoped, unspecified and multicast targets are prohibited")
        if not any(address in ipaddress.ip_network(cidr) for cidr in self.allowed_cidrs):
            raise ValueError(f"IP outside operator-approved scope: {value}")
        return str(address)

    def domain(self, value: str) -> str:
        name = value.lower().rstrip(".")
        if not name or any(character not in "abcdefghijklmnopqrstuvwxyz0123456789-." for character in name):
            raise ValueError("Use a domain name, not a URL or arbitrary target expression")
        if not any(name == allowed or name.endswith("." + allowed) for allowed in self.allowed_domains):
            raise ValueError(f"Domain outside operator-approved scope: {value}")
        return name

    def validate(self, spec: Assessment) -> None:
        if not spec.approved:
            raise ValueError("Explicit engagement authorization is required")
        for item in spec.inventory:
            for key, value in item.attributes.items():
                if len(value) > 2000 or any(secret in key.lower() for secret in ("password", "secret", "token", "credential", "api_key")):
                    raise ValueError("Inventory must not contain credentials/secrets or oversized attributes")
        if spec.mode != "ACTIVE":
            if spec.udp or spec.fingerprint_services:
                raise ValueError("Network scan options are exclusive to ACTIVE mode")
            if spec.targets:
                raise ValueError("PASSIVE/AUTHENTICATED inventory mode does not probe target expressions")
            if not spec.inventory:
                raise ValueError("This mode requires authorized supplied intelligence/inventory exports")
            return
        if not spec.targets or not self.nmap_version:
            raise ValueError("ACTIVE mode requires targets and RECON_NMAP_VERSION approval")
        if spec.udp and (not self.enable_udp or os.geteuid() != 0):
            raise ValueError("UDP requires enabled policy and a privileged isolated deployment")
        count = 0
        for value in spec.targets:
            if "/" in value:
                network = ipaddress.ip_network(value, strict=True)
                if network.num_addresses > self.max_targets:
                    raise ValueError("CIDR exceeds the bounded target limit")
                for address in network.hosts():
                    self.ip(str(address))
                    count += 1
            else:
                try:
                    ipaddress.ip_address(value)
                except ValueError:
                    self.domain(value)
                    count += 1
                else:
                    self.ip(value)
                    count += 1
        if count > self.max_targets:
            raise ValueError("Engagement target limit exceeded")
